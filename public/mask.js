// 보내기 전에 브라우저에서 이름 · 전화번호 · 사번을 가린다.
// maskPersonalInfo(text) → { text: 가린 문장, found: { 이름, 전화번호, 사번 } }
//
// 잡는 것
// - 전화번호: 휴대폰(010-1234-5678, +82 10 …), 지역번호 전화(02-123-4567, 031-…), 내선 번호(내선 1234)
// - 사번: '사번', '사원번호', '직원번호' 같은 말 바로 뒤의 번호
// - 이름: 성 + 이름 1~2글자 + 호칭(님·씨·책임·과장 …)  예) 김하나 책임님, 박민수님
//         '이름: 홍길동', '성명 홍길동', '담당자: 홍길동' 처럼 이름이라고 밝힌 것
// 못 잡는 것: 호칭 없이 이름만 쓴 경우(예: '김하나가 보냈어요'), 회사마다 다른 사번 형식
(function (root) {
  const SURNAMES = '김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주우구민진나지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉';
  const DOUBLE_SURNAMES = ['황보', '남궁', '제갈', '선우', '독고', '사공', '서문'];
  const TITLES = ['님', '씨', '책임', '선임', '수석', '과장', '차장', '부장', '대리', '사원', '주임', '팀장', '파트장', '그룹장', '실장', '본부장', '상무', '전무', '이사', '매니저', '프로', '연구원', '위원', '박사'];
  // 성으로 시작하지만 사람 이름이 아닌 흔한 말 (예: 고객님, 설계팀장, 이사님)
  const NOT_NAMES = new Set([
    '고객', '고객사', '설계', '기술', '기획', '개발', '공정', '평가', '생산', '연구', '연구원', '회로', '전원', '선배', '선생', '선임', '동료',
    '관리', '운영', '현장', '협력', '협력사', '문의', '신규', '기존', '전체', '국내', '해외', '사업', '인사', '재무', '보안', '시험', '검증',
    '장비', '제조', '양산', '신뢰', '분석', '주임', '전무', '이사', '부장', '차장', '사장', '사원', '위원', '박사', '기사', '원장', '소장',
    '조장', '반장', '국장', '공장', '공장장', '구매', '영업', '품질', '모듈', '패널', '구동', '공급', '여러', '해당', '이번', '지난', '다음',
    '모든', '이분', '그분', '저분', '이쪽', '저쪽', '그쪽', '우리', '저희', '담당', '소속', '상담', '고생', '감사', '정말', '조금', '이미',
    '전부', '지금', '오늘', '내일', '어제', '하나', '성능', '성공', '진행', '변경', '나중', '주간', '주말', '최종', '최신', '안녕',
  ]);

  const byLength = (a, b) => b.length - a.length;
  const titleAlt = [...TITLES].sort(byLength).join('|');
  const surnameAlt = [...DOUBLE_SURNAMES, `[${SURNAMES}]`].join('|');

  const RULES = [
    {
      kind: '전화번호',
      re: /(?<![\d])(?:\+82[-.\s]?1[016789]|01[016789])[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)/g,
      replace: () => '[전화번호]',
    },
    {
      kind: '전화번호',
      re: /(?<![\d.])0(?:2|[3-6][1-5]|70)[-.\s)]\s?\d{3,4}[-.\s]?\d{4}(?!\d)/g,
      replace: () => '[전화번호]',
    },
    {
      kind: '전화번호',
      re: /(내선|ext\.?)(\s*(?:번호)?\s*[:：]?\s*)\d{3,5}(?!\d)/gi,
      replace: (m, word, gap) => `${word}${gap}[전화번호]`,
    },
    {
      kind: '사번',
      re: /(사번|사원\s?번호|직원\s?번호|임직원\s?번호|emp(?:loyee)?\s*(?:id|no\.?))(\s*[:：]?\s*)[A-Za-z]{0,3}-?\d{4,10}(?!\d)/gi,
      replace: (m, word, gap) => `${word}${gap}[사번]`,
    },
    {
      kind: '이름',
      re: /(이름|성명|담당자?)(\s*[:：]?\s*)([가-힣]{2,4})(?![가-힣])/g,
      replace: (m, word, gap, name) => (NOT_NAMES.has(name) ? null : `${word}${gap}[이름]`),
    },
    {
      kind: '이름',
      re: new RegExp(`(^|[^가-힣])((?:${surnameAlt})[가-힣]{1,2})(\\s?)(${titleAlt})`, 'g'),
      replace: (m, before, name, space, title) => (NOT_NAMES.has(name) ? null : `${before}[이름]${space}${title}`),
    },
  ];

  function maskPersonalInfo(input) {
    const found = { 이름: 0, 전화번호: 0, 사번: 0 };
    let text = String(input ?? '');
    for (const rule of RULES) {
      text = text.replace(rule.re, (...args) => {
        const out = rule.replace(...args);
        if (out === null) return args[0];
        found[rule.kind]++;
        return out;
      });
    }
    return { text, found };
  }

  root.maskPersonalInfo = maskPersonalInfo;
})(typeof window !== 'undefined' ? window : globalThis);
